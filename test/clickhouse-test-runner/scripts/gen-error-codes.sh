#!/usr/bin/env bash
# Generates src/errorcodes.cpp from src/Common/ErrorCodes.cpp of a ClickHouse checkout.
# fetch-upstream.sh runs it after each checkout, so the error names of the test hints always
# match the tests. It needs only bash and sed.
#
# Usage: scripts/gen-error-codes.sh [<ClickHouse checkout>]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
checkout="${1:-${UPSTREAM_CLICKHOUSE_DIR:-${RUNNER_DIR}/.upstream/ClickHouse}}"
src_file="${checkout}/src/Common/ErrorCodes.cpp"

if [[ ! -f "${src_file}" ]]; then
  echo "Error: ${src_file} not found. Run scripts/fetch-upstream.sh first." >&2
  exit 1
fi
ref="$(cat "${checkout}/.upstream-ref" 2>/dev/null || git -C "${checkout}" rev-parse HEAD)"

out="${RUNNER_DIR}/src/errorcodes.cpp"
{
  echo "// Code generated by scripts/gen-error-codes.sh from ClickHouse ${ref}; DO NOT EDIT."
  echo
  echo '#include "hint.h"'
  echo
  echo '#include <unordered_map>'
  echo
  echo 'namespace runner {'
  echo
  echo 'namespace {'
  echo
  # The layout follows the repository's .clang-format (NamespaceIndentation: Inner).
  echo '    // The error names of src/Common/ErrorCodes.cpp and their codes. Test hints can name an error'
  echo '    // instead of giving its code.'
  echo '    const std::unordered_map<std::string, int> & errorCodes() {'
  echo '        static const std::unordered_map<std::string, int> codes = {'
  sed -n 's/^ *M(\([0-9][0-9]*\), *\([A-Z0-9_][A-Z0-9_]*\)).*/            {"\2", \1},/p' "${src_file}"
  echo '        };'
  echo '        return codes;'
  echo '    }'
  echo
  echo '} // namespace'
  echo
  echo 'std::optional<int> errorCodeByName(std::string_view name) {'
  echo '    const auto it = errorCodes().find(std::string(name));'
  echo '    if (it == errorCodes().end())'
  echo '        return std::nullopt;'
  echo '    return it->second;'
  echo '}'
  echo
  echo 'std::optional<std::string> errorNameByCode(int code) {'
  echo '    static const auto names = [] {'
  echo '        std::unordered_map<int, std::string> m;'
  echo '        for (const auto & [name, c] : errorCodes())'
  echo '            m.emplace(c, name);'
  echo '        return m;'
  echo '    }();'
  echo '    const auto it = names.find(code);'
  echo '    if (it == names.end())'
  echo '        return std::nullopt;'
  echo '    return it->second;'
  echo '}'
  echo
  echo '} // namespace runner'
} > "${out}"
echo "Wrote $(grep -c '^            {"' "${out}") error codes from ${ref} to ${out}" >&2
